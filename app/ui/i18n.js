let language = "en";

export function setLanguage(lang) {
  language = STRINGS[lang] ? lang : "en";
  document.documentElement.lang = language === "pt" ? "pt-BR" : "en";
}

export function getLanguage() {
  return language;
}

export function t(key, vars = {}) {
  const text = STRINGS[language][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}

/** "1 conflict" / "2 conflicts" from a key and its "Many" twin */
export function tn(key, n) {
  return t(n === 1 ? key : `${key}Many`, { n });
}

/** Static text in the markup: data-t="key" */
export function applyStatic(root = document) {
  for (const node of root.querySelectorAll("[data-t]")) node.textContent = t(node.dataset.t);
}

export function duration(ms) {
  const minutes = Math.floor(ms / 60000);
  if (minutes < 1) return t("justNow");
  if (minutes < 60) return t("min", { n: minutes });
  return t("hours", { h: Math.floor(minutes / 60), m: minutes % 60 });
}
