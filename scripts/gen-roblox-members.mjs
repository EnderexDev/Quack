// Writes src/analyze/robloxMembers.ts from Roblox's API dump: the name of every member
// (property, function, event, callback) of every class, and each class's own members with its
// superclass. The analyzer uses the names to tell `humanoid.Died` or `part.Size` (a member) from
// `folder.Missing` (a child that is not there), and the classes to tell `part.Anchord` or a
// RemoteFunction's `:FireServer()` (no such member on that class) from a real member.
//
//   node scripts/gen-roblox-members.mjs [API-Dump.json]
//
// Without a file it downloads the dump Roblox-Client-Tracker keeps current. A name Roblox adds
// later is unknown until this runs again: the analyzer can then report `x.NewEvent` as a missing
// child or member, so run it when a false finding names an engine member.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const URL_DUMP = "https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/API-Dump.json";

export function memberNames(dump) {
  const names = new Set();
  for (const c of dump.Classes ?? []) for (const m of c.Members ?? []) names.add(m.Name);
  return [...names].sort();
}

export function render(dump, stamp) {
  const names = memberNames(dump);
  const lines = [];
  for (let i = 0; i < names.length; i += 10) lines.push(`  ${names.slice(i, i + 10).map((n) => JSON.stringify(n)).join(", ")},`);
  const classes = [...(dump.Classes ?? [])]
    .sort((a, b) => (a.Name < b.Name ? -1 : a.Name > b.Name ? 1 : 0))
    .map((c) => `  ${JSON.stringify(c.Name)}: [${JSON.stringify(c.Superclass ?? "")}, ${JSON.stringify([...new Set((c.Members ?? []).map((m) => m.Name))].sort())}],`);
  return `// Generated by scripts/gen-roblox-members.mjs from Roblox's API dump (${stamp}): do not edit.
export const ROBLOX_MEMBERS: ReadonlySet<string> = new Set([
${lines.join("\n")}
]);

/** Each class: its superclass and its own members (not the inherited ones) */
export const ROBLOX_CLASSES: Readonly<Record<string, readonly [string, readonly string[]]>> = {
${classes.join("\n")}
};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = process.argv[2];
  const text = file ? fs.readFileSync(file, "utf8") : await (await fetch(URL_DUMP)).text();
  const dump = JSON.parse(text);
  const stamp = `${dump.Classes.length} classes, ${new Date().toISOString().slice(0, 10)}`;
  const out = path.join(repo, "src/analyze/robloxMembers.ts");
  fs.writeFileSync(out, render(dump, stamp));
  console.log(`wrote ${path.relative(repo, out)}: ${memberNames(dump).length} names, ${dump.Classes.length} classes`);
}
